from datetime import datetime, timezone
import json
from typing import Any, Dict
from app.extensions import db


class InfrastructureDependency(db.Model):
    """
    Relational infrastructure supply or distribution dependency
    (e.g. Electrical Panel, Water Distribution Main, Network Switch).
    """
    __tablename__ = "infrastructure_dependencies"

    id = db.Column(db.Integer, primary_key=True)
    dependency_identifier = db.Column(db.String(80), unique=True, nullable=False, index=True)
    name = db.Column(db.String(150), nullable=False)
    dependency_type = db.Column(db.String(50), nullable=False, index=True)  # 'electrical_supply', 'water_supply', 'network'
    building = db.Column(db.String(100), nullable=False, index=True)
    description = db.Column(db.Text, nullable=True)
    is_synthetic = db.Column(db.Boolean, nullable=False, default=False)  # True for demo/synthetic fixtures
    created_at = db.Column(db.DateTime, nullable=False, default=lambda: datetime.now(timezone.utc))

    # Relationships
    locations = db.relationship("DependencyLocation", backref="dependency", cascade="all, delete-orphan", lazy="joined")
    suggestions = db.relationship("RadarSuggestion", backref="dependency", lazy="dynamic")

    def __repr__(self) -> str:
        return f"<InfrastructureDependency {self.dependency_identifier} ({self.dependency_type}) in {self.building}>"


class DependencyLocation(db.Model):
    """
    Associates a specific room, area, or asset within a building to an infrastructure dependency.
    """
    __tablename__ = "dependency_locations"

    id = db.Column(db.Integer, primary_key=True)
    dependency_id = db.Column(
        db.Integer,
        db.ForeignKey("infrastructure_dependencies.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    location_name = db.Column(db.String(120), nullable=False)  # e.g., 'Computer Lab', 'Classroom 102', 'Water Dispenser Area'
    room = db.Column(db.String(80), nullable=True, index=True)  # e.g., 'Lab 101', '102'
    asset_name = db.Column(db.String(120), nullable=True)  # e.g., 'Workstation Sub-Circuit', 'Display Power Feed'
    is_synthetic = db.Column(db.Boolean, nullable=False, default=False)
    created_at = db.Column(db.DateTime, nullable=False, default=lambda: datetime.now(timezone.utc))

    def __repr__(self) -> str:
        return f"<DependencyLocation {self.location_name} (room={self.room}) -> dep_id={self.dependency_id}>"


class RadarSuggestion(db.Model):
    """
    A proposed, human-reviewed incident correlation suggestion generated by the Incident Radar service.
    """
    __tablename__ = "radar_suggestions"

    id = db.Column(db.Integer, primary_key=True)
    suggestion_type = db.Column(db.String(50), nullable=False, index=True)  # 'shared_dependency' or 'location_time_cluster'
    status = db.Column(
        db.String(40), nullable=False, default="pending_review", index=True
    )  # 'pending_review', 'confirmed_for_review', 'rejected'
    
    building = db.Column(db.String(100), nullable=False, index=True)
    dependency_id = db.Column(
        db.Integer,
        db.ForeignKey("infrastructure_dependencies.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )
    
    # Human-readable advisory headline and summary
    headline = db.Column(db.String(255), nullable=False)
    summary = db.Column(db.Text, nullable=False)
    
    # Fingerprint signature to prevent duplicate suggestions on re-runs
    fingerprint = db.Column(db.String(64), unique=True, nullable=False, index=True)

    # Serialized evidence snapshot (timestamps, location matches, symptoms, missing info, analysis method)
    evidence_json = db.Column(db.Text, nullable=False)
    analysis_version = db.Column(db.String(30), nullable=False, default="radar_v1.0")

    # Review workflow fields
    review_decision = db.Column(db.String(40), nullable=True)  # 'confirmed', 'rejected'
    reviewed_by_user_id = db.Column(db.Integer, db.ForeignKey("users.id", ondelete="SET NULL"), nullable=True)
    reviewed_at = db.Column(db.DateTime, nullable=True)
    review_notes = db.Column(db.Text, nullable=True)
    clarification_notes = db.Column(db.Text, nullable=True)

    created_at = db.Column(db.DateTime, nullable=False, default=lambda: datetime.now(timezone.utc), index=True)
    updated_at = db.Column(
        db.DateTime,
        nullable=False,
        default=lambda: datetime.now(timezone.utc),
        onupdate=lambda: datetime.now(timezone.utc),
    )

    # Relationships
    reports = db.relationship("RadarSuggestionReport", backref="suggestion", cascade="all, delete-orphan", lazy="joined")
    reviewer = db.relationship("User", foreign_keys=[reviewed_by_user_id])

    @property
    def evidence(self) -> Dict[str, Any]:
        try:
            return json.loads(self.evidence_json) if self.evidence_json else {}
        except Exception:
            return {}

    def __repr__(self) -> str:
        return f"<RadarSuggestion {self.id} type={self.suggestion_type} status={self.status} bldg={self.building}>"


class RadarSuggestionReport(db.Model):
    """
    Associates a complaint report with a radar suggestion.
    """
    __tablename__ = "radar_suggestion_reports"

    id = db.Column(db.Integer, primary_key=True)
    suggestion_id = db.Column(
        db.Integer,
        db.ForeignKey("radar_suggestions.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    complaint_id = db.Column(
        db.Integer,
        db.ForeignKey("complaints.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    detected_symptom = db.Column(db.String(80), nullable=True)
    matched_asset_name = db.Column(db.String(120), nullable=True)
    created_at = db.Column(db.DateTime, nullable=False, default=lambda: datetime.now(timezone.utc))

    # Relationship to Complaint
    complaint = db.relationship("Complaint", lazy="joined")

    def __repr__(self) -> str:
        return f"<RadarSuggestionReport sugg={self.suggestion_id} comp={self.complaint_id}>"

